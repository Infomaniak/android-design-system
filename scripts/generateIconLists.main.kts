#!/usr/bin/env kotlin

import java.io.File

/*
 * Scans the Medium icon package and generates `AllMediumIcons.kt`, which exposes every
 * `EsdsIcons.Medium.*` icon in a single list (e.g. to display them all in a preview grid).
 *
 * Re-run this script whenever icons are added, renamed or removed:
 *   kotlin scripts/generateIconLists.main.kts
 */

val repoRoot: File = generateSequence(File(System.getProperty("user.dir")).absoluteFile) { it.parentFile }
    .firstOrNull { File(it, "settings.gradle.kts").exists() }
    ?: error("Could not locate the repository root (no settings.gradle.kts found in any parent folder).")

val iconsDir = repoRoot.resolve("Icons/src/commonMain/kotlin/com/infomaniak/designsystem/icons")
val iconDeclaration = Regex("""val EsdsIcons\.Medium\.(\w+): ImageVector""")

val iconNames = iconsDir.resolve("imagevector/medium")
    .listFiles { file -> file.extension == "kt" }!!
    .mapNotNull { iconDeclaration.find(it.readText())?.groupValues?.get(1) }
    .sorted()

val output = buildString {
    appendLine("// Auto-generated by scripts/generateIconLists.main.kts. Do not edit manually.")
    appendLine()
    appendLine("package com.infomaniak.designsystem.icons")
    appendLine()
    appendLine("import androidx.compose.ui.graphics.vector.ImageVector")
    iconNames.forEach { appendLine("import com.infomaniak.designsystem.icons.imagevector.medium.$it") }
    appendLine()
    appendLine("internal val AllMediumIcons: List<ImageVector>")
    appendLine("    get() = listOf(")
    iconNames.forEach { appendLine("        EsdsIcons.Medium.$it,") }
    appendLine("    )")
}

iconsDir.resolve("AllMediumIcons.kt").writeText(output)
println("Generated AllMediumIcons.kt with ${iconNames.size} icons.")
