#!/usr/bin/env kotlin

import java.io.File

/**
 * The repository root, resolved independently of the current working directory so the script can be
 * run from anywhere (e.g. the repo root or the /scripts folder).
 */
val repoRoot: File = generateSequence(File(System.getProperty("user.dir")).absoluteFile) { it.parentFile }
    .firstOrNull { File(it, "settings.gradle.kts").exists() }
    ?: error("Could not locate the repository root (no settings.gradle.kts found in any parent folder).")

/*
 * Generates one `Symbol` file per icon in `Icons/…/icons/symbols/`, grouping the five sized
 * `ImageVector`s (generated in `Icons/…/icons/imagevector/<size>/`) behind a single public
 * `EsdsIcons.<Name>: Symbol` entry point.
 *
 * Every icon must exist in every size folder, otherwise the script fails.
 */

val basePackage = "com.infomaniak.designsystem.icons"
val iconsDir = File(repoRoot, "Icons/src/commonMain/kotlin/${basePackage.replace('.', '/')}")
val imageVectorDir = File(iconsDir, "imagevector")
val symbolsDir = File(iconsDir, "symbols")

// Size object name in EsdsIcons to sub-package name in imagevector/
val sizes = listOf("ExtraSmall", "Small", "Medium", "Large", "ExtraLarge").associateWith { it.lowercase() }

fun iconNames(sizePackage: String): Set<String> {
    val dir = File(imageVectorDir, sizePackage)
    require(dir.isDirectory) { "Missing icon folder: ${dir.path}" }
    return dir.listFiles { file -> file.extension == "kt" }!!.map { it.nameWithoutExtension }.toSortedSet()
}

val namesBySize = sizes.mapValues { (_, sizePackage) -> iconNames(sizePackage) }
val allNames = namesBySize.values.flatten().toSortedSet()
namesBySize.forEach { (size, names) ->
    val missing = allNames - names
    require(missing.isEmpty()) { "Icons missing in $size: $missing" }
}

val generatedHeader = "// This file is auto-generated by scripts/generateIconSymbols.main.kts. Do not edit it manually."

fun symbolFile(name: String): String = buildString {
    appendLine(generatedHeader)
    appendLine("package $basePackage.symbols")
    appendLine()
    appendLine("import androidx.compose.ui.graphics.vector.ImageVector")
    appendLine("import $basePackage.EsdsIcons")
    sizes.values.forEach { sizePackage -> appendLine("import $basePackage.imagevector.$sizePackage.$name") }
    appendLine()
    appendLine("val EsdsIcons.$name: Symbol get() = ${name}Symbol")
    appendLine()
    appendLine("private object ${name}Symbol : Symbol {")
    sizes.keys.forEach { size -> appendLine("    override val $size: ImageVector get() = EsdsIcons.$size.$name") }
    appendLine("}")
}

symbolsDir.mkdirs()
// Only remove previously generated files, Symbol.kt lives in the same folder
symbolsDir.listFiles { file -> file.extension == "kt" && file.readText().startsWith(generatedHeader) }!!.forEach { it.delete() }
allNames.forEach { name -> File(symbolsDir, "$name.kt").writeText(symbolFile(name)) }

println("Generated ${allNames.size} symbols in ${symbolsDir.relativeTo(repoRoot).path}")
